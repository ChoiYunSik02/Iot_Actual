def bump_body(prs, d=1.5):
    """제목(24pt 이상)·eyebrow(자간 있음)·페이지 번호를 뺀 본문과 표의 글씨를 d pt 키운다."""
    def up(tf):
        for p in tf.paragraphs:
            for r in p.runs:
                if r.font.size and r.font.size.pt < 24 and r._r.get_or_add_rPr().get('spc') is None:
                    r.font.size = Pt(r.font.size.pt + d)
    for sl in prs.slides:
        for sh in sl.shapes:
            if sh.has_text_frame and not (sh.top > Inches(7.0)): up(sh.text_frame)
            elif getattr(sh, 'has_table', False) and sh.has_table:
                for row in sh.table.rows:
                    for c in row.cells: up(c.text_frame)


bump_body(prs)


def scale_summary(sl, k=1.3):
    """정리 쪽의 카드 본문과 한 줄 결론 글씨를 k배로 키운다."""
    for sh in sl.shapes:
        if sh.has_text_frame and sh.text_frame.text.startswith(('· ', '제안 규칙은')):
            for p in sh.text_frame.paragraphs:
                for r in p.runs: r.font.size = Pt(r.font.size.pt * k)


