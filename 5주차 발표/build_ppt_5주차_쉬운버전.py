def pic(s, name, x, y, w, h):
    path = os.path.join(FIG, name)
    iw, ih = Image.open(path).size
    r = min(w / iw, h / ih)
    s.shapes.add_picture(path, Inches(x + (w - iw * r) / 2), Inches(y + (h - ih * r) / 2),
                         Inches(iw * r), Inches(ih * r))


