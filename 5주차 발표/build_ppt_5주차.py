def pic(s, name, x, y, w, h):
    """그림을 상자 안에 비율 유지로 넣고 가운데 정렬."""
    path = os.path.join(FIG, name)
    iw, ih = Image.open(path).size
    r = min(w / iw, h / ih)
    pw, ph = iw * r, ih * r
    s.shapes.add_picture(path, Inches(x + (w - pw) / 2), Inches(y + (h - ph) / 2),
                         Inches(pw), Inches(ph))


